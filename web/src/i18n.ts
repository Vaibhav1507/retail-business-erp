const catalogues: Record<Lang, Record<MessageKey, string>> = { en, hi }
let current: Lang = 'en'

export function setLanguage(lang: Lang) { current = lang }
export function getLanguage(): Lang { return current }
export function toLang(value: string | null | undefined): Lang { return value === 'hi' ? 'hi' : 'en' }

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const text = catalogues[current][key] ?? en[key]
  return params ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m)) : text
}

const locale = () => (current === 'hi' ? 'hi-IN' : 'en-IN')

export function formatInr(amount: number): string {
  return new Intl.NumberFormat(locale(), { style: 'currency', currency: 'INR', minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(amount)
}

export function formatDate(value: string | number | Date): string {
  return new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(value))
}
